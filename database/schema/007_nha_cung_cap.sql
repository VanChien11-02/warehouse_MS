CREATE TABLE dbo.NHA_CUNG_CAP (
    MaNCC CHAR(6) NOT NULL CONSTRAINT PK_NHA_CUNG_CAP PRIMARY KEY,
    TenNCC NVARCHAR(255) NOT NULL,
    DiaChi NVARCHAR(500) NULL,
    SDT VARCHAR(20) NULL,
    Email VARCHAR(255) NULL,
    CONSTRAINT CK_NHA_CUNG_CAP_TEN_NOT_BLANK CHECK (LEN(LTRIM(RTRIM(TenNCC))) > 0)
);
