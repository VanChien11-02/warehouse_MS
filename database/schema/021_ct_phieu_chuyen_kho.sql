CREATE TABLE dbo.CT_PHIEU_CHUYEN_KHO (
    MaPCK CHAR(6) NOT NULL,
    MaLo CHAR(6) NOT NULL,
    MaViTriNguon CHAR(6) NOT NULL,
    MaViTriDich CHAR(6) NOT NULL,
    SoLuong INT NOT NULL,
    CONSTRAINT PK_CT_PHIEU_CHUYEN_KHO
        PRIMARY KEY (MaPCK, MaLo, MaViTriNguon, MaViTriDich),
    CONSTRAINT FK_CT_PHIEU_CHUYEN_KHO_PCK FOREIGN KEY (MaPCK)
        REFERENCES dbo.PHIEU_CHUYEN_KHO (MaPCK),
    CONSTRAINT FK_CT_PHIEU_CHUYEN_KHO_LO FOREIGN KEY (MaLo)
        REFERENCES dbo.LO_HANG (MaLo),
    CONSTRAINT FK_CT_PHIEU_CHUYEN_KHO_NGUON FOREIGN KEY (MaViTriNguon)
        REFERENCES dbo.VI_TRI_KHO (MaViTri),
    CONSTRAINT FK_CT_PHIEU_CHUYEN_KHO_DICH FOREIGN KEY (MaViTriDich)
        REFERENCES dbo.VI_TRI_KHO (MaViTri),
    CONSTRAINT CK_CT_PHIEU_CHUYEN_KHO_SO_LUONG CHECK (SoLuong > 0),
    CONSTRAINT CK_CT_PHIEU_CHUYEN_KHO_VI_TRI CHECK (MaViTriNguon <> MaViTriDich)
);
