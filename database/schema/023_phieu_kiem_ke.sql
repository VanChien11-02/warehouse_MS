CREATE TABLE dbo.PHIEU_KIEM_KE (
    MaPKK CHAR(6) NOT NULL CONSTRAINT PK_PHIEU_KIEM_KE PRIMARY KEY,
    NgayKiemKe DATETIME2(3) NOT NULL
        CONSTRAINT DF_PHIEU_KIEM_KE_NGAY DEFAULT (SYSUTCDATETIME()),
    MaNV CHAR(6) NOT NULL,
    MaViTri CHAR(6) NOT NULL,
    TrangThai NVARCHAR(20) NOT NULL
        CONSTRAINT DF_PHIEU_KIEM_KE_TRANG_THAI DEFAULT (N'NHAP'),
    GhiChu NVARCHAR(1000) NULL,
    NgayHoanTat DATETIME2(3) NULL,
    CONSTRAINT FK_PHIEU_KIEM_KE_NV FOREIGN KEY (MaNV)
        REFERENCES dbo.NHAN_VIEN (MaNV),
    CONSTRAINT FK_PHIEU_KIEM_KE_VI_TRI FOREIGN KEY (MaViTri)
        REFERENCES dbo.VI_TRI_KHO (MaViTri),
    CONSTRAINT CK_PHIEU_KIEM_KE_TRANG_THAI
        CHECK (TrangThai IN (N'NHAP', N'DA_HOAN_THANH', N'DA_HUY')),
    CONSTRAINT CK_PHIEU_KIEM_KE_HOAN_TAT CHECK (
        (TrangThai = N'DA_HOAN_THANH' AND NgayHoanTat IS NOT NULL)
        OR (TrangThai <> N'DA_HOAN_THANH' AND NgayHoanTat IS NULL)
    )
);
