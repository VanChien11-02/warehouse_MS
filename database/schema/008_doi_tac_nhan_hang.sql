CREATE TABLE dbo.DOI_TAC_NHAN_HANG (
    MaDTNH CHAR(6) NOT NULL CONSTRAINT PK_DOI_TAC_NHAN_HANG PRIMARY KEY,
    TenDoiTac NVARCHAR(255) NOT NULL,
    LoaiDoiTac NVARCHAR(50) NOT NULL,
    DiaChi NVARCHAR(500) NULL,
    SDT VARCHAR(20) NULL,
    Email VARCHAR(255) NULL,
    CONSTRAINT CK_DOI_TAC_NHAN_HANG_TEN_NOT_BLANK
        CHECK (LEN(LTRIM(RTRIM(TenDoiTac))) > 0),
    CONSTRAINT CK_DOI_TAC_NHAN_HANG_LOAI_NOT_BLANK
        CHECK (LEN(LTRIM(RTRIM(LoaiDoiTac))) > 0)
);
