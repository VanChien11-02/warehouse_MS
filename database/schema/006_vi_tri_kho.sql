CREATE TABLE dbo.VI_TRI_KHO (
    MaViTri CHAR(6) NOT NULL CONSTRAINT PK_VI_TRI_KHO PRIMARY KEY,
    MaKhuVuc CHAR(6) NOT NULL,
    TenViTri NVARCHAR(255) NOT NULL,
    SucChua INT NOT NULL,
    LoaiViTri NVARCHAR(20) NOT NULL,
    CONSTRAINT FK_VI_TRI_KHO_KHU_VUC FOREIGN KEY (MaKhuVuc)
        REFERENCES dbo.KHU_VUC (MaKhuVuc),
    CONSTRAINT UQ_VI_TRI_KHO_TEN UNIQUE (MaKhuVuc, TenViTri),
    CONSTRAINT CK_VI_TRI_KHO_SUC_CHUA CHECK (SucChua >= 0),
    CONSTRAINT CK_VI_TRI_KHO_LOAI
        CHECK (LoaiViTri IN (N'Lưu trữ', N'Lấy hàng', N'Hư hỏng'))
);
