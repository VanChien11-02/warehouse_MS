CREATE TABLE dbo.CT_PHIEU_XUAT (
    MaPX CHAR(6) NOT NULL,
    MaLo CHAR(6) NOT NULL,
    MaViTri CHAR(6) NOT NULL,
    SoLuong INT NOT NULL,
    DonGiaXuat DECIMAL(19, 4) NOT NULL,
    CONSTRAINT PK_CT_PHIEU_XUAT PRIMARY KEY (MaPX, MaLo, MaViTri),
    CONSTRAINT FK_CT_PHIEU_XUAT_PX FOREIGN KEY (MaPX)
        REFERENCES dbo.PHIEU_XUAT (MaPX),
    CONSTRAINT FK_CT_PHIEU_XUAT_LO FOREIGN KEY (MaLo)
        REFERENCES dbo.LO_HANG (MaLo),
    CONSTRAINT FK_CT_PHIEU_XUAT_VI_TRI FOREIGN KEY (MaViTri)
        REFERENCES dbo.VI_TRI_KHO (MaViTri),
    CONSTRAINT CK_CT_PHIEU_XUAT_SO_LUONG CHECK (SoLuong > 0),
    CONSTRAINT CK_CT_PHIEU_XUAT_DON_GIA CHECK (DonGiaXuat >= 0)
);
