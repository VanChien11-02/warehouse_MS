CREATE TABLE dbo.CT_PHIEU_TRA_HANG (
    MaPTH CHAR(6) NOT NULL,
    MaLo CHAR(6) NOT NULL,
    MaViTri CHAR(6) NOT NULL,
    SoLuong INT NOT NULL,
    TinhTrang NVARCHAR(20) NOT NULL,
    CONSTRAINT PK_CT_PHIEU_TRA_HANG PRIMARY KEY (MaPTH, MaLo),
    CONSTRAINT FK_CT_PHIEU_TRA_HANG_PTH FOREIGN KEY (MaPTH)
        REFERENCES dbo.PHIEU_TRA_HANG (MaPTH),
    CONSTRAINT FK_CT_PHIEU_TRA_HANG_LO FOREIGN KEY (MaLo)
        REFERENCES dbo.LO_HANG (MaLo),
    CONSTRAINT FK_CT_PHIEU_TRA_HANG_VI_TRI FOREIGN KEY (MaViTri)
        REFERENCES dbo.VI_TRI_KHO (MaViTri),
    CONSTRAINT CK_CT_PHIEU_TRA_HANG_SO_LUONG CHECK (SoLuong > 0),
    CONSTRAINT CK_CT_PHIEU_TRA_HANG_TINH_TRANG
        CHECK (TinhTrang IN (N'Tốt', N'Hư hỏng'))
);
