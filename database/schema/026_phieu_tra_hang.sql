CREATE TABLE dbo.PHIEU_TRA_HANG (
    MaPTH CHAR(6) NOT NULL CONSTRAINT PK_PHIEU_TRA_HANG PRIMARY KEY,
    NgayTra DATETIME2(3) NOT NULL
        CONSTRAINT DF_PHIEU_TRA_HANG_NGAY DEFAULT (SYSUTCDATETIME()),
    MaPX CHAR(6) NOT NULL,
    MaNV CHAR(6) NOT NULL,
    TrangThai NVARCHAR(20) NOT NULL
        CONSTRAINT DF_PHIEU_TRA_HANG_TRANG_THAI DEFAULT (N'NHAP'),
    GhiChu NVARCHAR(1000) NULL,
    NgayHoanTat DATETIME2(3) NULL,
    CONSTRAINT FK_PHIEU_TRA_HANG_PX FOREIGN KEY (MaPX)
        REFERENCES dbo.PHIEU_XUAT (MaPX),
    CONSTRAINT FK_PHIEU_TRA_HANG_NV FOREIGN KEY (MaNV)
        REFERENCES dbo.NHAN_VIEN (MaNV),
    CONSTRAINT CK_PHIEU_TRA_HANG_TRANG_THAI
        CHECK (TrangThai IN (N'NHAP', N'DA_HOAN_THANH', N'DA_HUY')),
    CONSTRAINT CK_PHIEU_TRA_HANG_HOAN_TAT CHECK (
        (TrangThai = N'DA_HOAN_THANH' AND NgayHoanTat IS NOT NULL)
        OR (TrangThai <> N'DA_HOAN_THANH' AND NgayHoanTat IS NULL)
    )
);
CREATE INDEX IX_PHIEU_TRA_HANG_PX ON dbo.PHIEU_TRA_HANG (MaPX, TrangThai);
