CREATE TABLE dbo.CT_KIEM_KE (
    MaPKK CHAR(6) NOT NULL,
    MaLo CHAR(6) NOT NULL,
    SoLuongHeThong INT NOT NULL,
    SoLuongThucTe INT NULL,
    LyDoChenhLech NVARCHAR(500) NULL,
    CONSTRAINT PK_CT_KIEM_KE PRIMARY KEY (MaPKK, MaLo),
    CONSTRAINT FK_CT_KIEM_KE_PKK FOREIGN KEY (MaPKK)
        REFERENCES dbo.PHIEU_KIEM_KE (MaPKK),
    CONSTRAINT FK_CT_KIEM_KE_LO FOREIGN KEY (MaLo)
        REFERENCES dbo.LO_HANG (MaLo),
    CONSTRAINT CK_CT_KIEM_KE_SO_LUONG_HE_THONG CHECK (SoLuongHeThong >= 0),
    CONSTRAINT CK_CT_KIEM_KE_SO_LUONG_THUC_TE
        CHECK (SoLuongThucTe IS NULL OR SoLuongThucTe >= 0)
);
