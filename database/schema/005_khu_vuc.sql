CREATE TABLE dbo.KHU_VUC (
    MaKhuVuc CHAR(6) NOT NULL CONSTRAINT PK_KHU_VUC PRIMARY KEY,
    MaKho CHAR(6) NOT NULL,
    TenKhuVuc NVARCHAR(255) NOT NULL,
    LoaiKhuVuc NVARCHAR(20) NOT NULL,
    CONSTRAINT FK_KHU_VUC_KHO FOREIGN KEY (MaKho)
        REFERENCES dbo.KHO (MaKho),
    CONSTRAINT UQ_KHU_VUC_TEN UNIQUE (MaKho, TenKhuVuc),
    CONSTRAINT CK_KHU_VUC_LOAI
        CHECK (LoaiKhuVuc IN (N'Khô', N'Mát', N'Đông lạnh'))
);
