CREATE TABLE dbo.PHIEU_XUAT (
    MaPX CHAR(6) NOT NULL CONSTRAINT PK_PHIEU_XUAT PRIMARY KEY,
    NgayXuat DATETIME2(3) NOT NULL
        CONSTRAINT DF_PHIEU_XUAT_NGAY DEFAULT (SYSUTCDATETIME()),
    MaDTNH CHAR(6) NOT NULL,
    MaNV CHAR(6) NOT NULL,
    TrangThai NVARCHAR(20) NOT NULL
        CONSTRAINT DF_PHIEU_XUAT_TRANG_THAI DEFAULT (N'NHAP'),
    GhiChu NVARCHAR(1000) NULL,
    NgayHoanTat DATETIME2(3) NULL,
    CONSTRAINT FK_PHIEU_XUAT_DT FOREIGN KEY (MaDTNH)
        REFERENCES dbo.DOI_TAC_NHAN_HANG (MaDTNH),
    CONSTRAINT FK_PHIEU_XUAT_NV FOREIGN KEY (MaNV)
        REFERENCES dbo.NHAN_VIEN (MaNV),
    CONSTRAINT CK_PHIEU_XUAT_TRANG_THAI
        CHECK (TrangThai IN (N'NHAP', N'DA_HOAN_THANH', N'DA_HUY')),
    CONSTRAINT CK_PHIEU_XUAT_HOAN_TAT CHECK (
        (TrangThai = N'DA_HOAN_THANH' AND NgayHoanTat IS NOT NULL)
        OR (TrangThai <> N'DA_HOAN_THANH' AND NgayHoanTat IS NULL)
    )
);
