CREATE TABLE dbo.TAI_KHOAN (
    MaTK CHAR(6) NOT NULL CONSTRAINT PK_TAI_KHOAN PRIMARY KEY,
    MaNV CHAR(6) NOT NULL CONSTRAINT UQ_TAI_KHOAN_NHAN_VIEN UNIQUE,
    MaRole CHAR(6) NOT NULL,
    TenTK NVARCHAR(100) NOT NULL CONSTRAINT UQ_TAI_KHOAN_TEN UNIQUE,
    MatKhauHash VARCHAR(255) NOT NULL,
    TrangThai BIT NOT NULL CONSTRAINT DF_TAI_KHOAN_TRANG_THAI DEFAULT (1),
    CONSTRAINT FK_TAI_KHOAN_NHAN_VIEN FOREIGN KEY (MaNV)
        REFERENCES dbo.NHAN_VIEN (MaNV),
    CONSTRAINT FK_TAI_KHOAN_ROLE FOREIGN KEY (MaRole)
        REFERENCES dbo.[ROLE] (MaRole),
    CONSTRAINT CK_TAI_KHOAN_TEN_NOT_BLANK CHECK (LEN(LTRIM(RTRIM(TenTK))) > 0),
    CONSTRAINT CK_TAI_KHOAN_HASH_NOT_BLANK CHECK (LEN(LTRIM(RTRIM(MatKhauHash))) > 0)
);
