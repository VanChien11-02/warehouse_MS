CREATE TABLE dbo.NHAN_VIEN (
    MaNV CHAR(6) NOT NULL CONSTRAINT PK_NHAN_VIEN PRIMARY KEY,
    TenNV NVARCHAR(255) NOT NULL,
    SDT VARCHAR(20) NULL,
    GioiTinh NVARCHAR(10) NULL,
    NgaySinh DATE NULL,
    DiaChi NVARCHAR(500) NULL,
    Luong DECIMAL(19, 4) NULL,
    NgayVaoLam DATE NOT NULL,
    DangLamViec BIT NOT NULL CONSTRAINT DF_NHAN_VIEN_DANG_LAM DEFAULT (1),
    CONSTRAINT CK_NHAN_VIEN_TEN_NOT_BLANK CHECK (LEN(LTRIM(RTRIM(TenNV))) > 0),
    CONSTRAINT CK_NHAN_VIEN_GIOI_TINH CHECK (GioiTinh IN (N'Nam', N'Nữ', N'Khác')),
    CONSTRAINT CK_NHAN_VIEN_LUONG CHECK (Luong >= 0)
);
