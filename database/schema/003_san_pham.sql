CREATE TABLE dbo.SAN_PHAM (
    MaSP CHAR(6) NOT NULL CONSTRAINT PK_SAN_PHAM PRIMARY KEY,
    TenSP NVARCHAR(255) NOT NULL,
    MaLoai CHAR(6) NOT NULL,
    MaDVT CHAR(6) NOT NULL,
    GiaNhapMacDinh DECIMAL(19, 4) NOT NULL
        CONSTRAINT DF_SAN_PHAM_GIA_NHAP DEFAULT (0),
    GiaBanMacDinh DECIMAL(19, 4) NOT NULL
        CONSTRAINT DF_SAN_PHAM_GIA_BAN DEFAULT (0),
    CONSTRAINT FK_SAN_PHAM_LOAI FOREIGN KEY (MaLoai)
        REFERENCES dbo.LOAI_SAN_PHAM (MaLoai),
    CONSTRAINT FK_SAN_PHAM_DVT FOREIGN KEY (MaDVT)
        REFERENCES dbo.DON_VI_TINH (MaDVT),
    CONSTRAINT CK_SAN_PHAM_GIA_NHAP CHECK (GiaNhapMacDinh >= 0),
    CONSTRAINT CK_SAN_PHAM_GIA_BAN CHECK (GiaBanMacDinh >= 0)
);
