CREATE TABLE dbo.PHIEU_CHUYEN_KHO (
    MaPCK CHAR(6) NOT NULL CONSTRAINT PK_PHIEU_CHUYEN_KHO PRIMARY KEY,
    NgayChuyen DATETIME2(3) NOT NULL
        CONSTRAINT DF_PHIEU_CHUYEN_KHO_NGAY DEFAULT (SYSUTCDATETIME()),
    MaNV CHAR(6) NOT NULL,
    TrangThai NVARCHAR(20) NOT NULL
        CONSTRAINT DF_PHIEU_CHUYEN_KHO_TRANG_THAI DEFAULT (N'NHAP'),
    GhiChu NVARCHAR(1000) NULL,
    NgayHoanTat DATETIME2(3) NULL,
    CONSTRAINT FK_PHIEU_CHUYEN_KHO_NV FOREIGN KEY (MaNV)
        REFERENCES dbo.NHAN_VIEN (MaNV),
    CONSTRAINT CK_PHIEU_CHUYEN_KHO_TRANG_THAI
        CHECK (TrangThai IN (N'NHAP', N'DA_HOAN_THANH', N'DA_HUY')),
    CONSTRAINT CK_PHIEU_CHUYEN_KHO_HOAN_TAT CHECK (
        (TrangThai = N'DA_HOAN_THANH' AND NgayHoanTat IS NOT NULL)
        OR (TrangThai <> N'DA_HOAN_THANH' AND NgayHoanTat IS NULL)
    )
);
