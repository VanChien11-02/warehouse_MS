:ON ERROR EXIT
IF OBJECT_ID(N'dbo.PHIEU_NHAP', N'U') IS NOT NULL
    OR OBJECT_ID(N'dbo.CT_PHIEU_NHAP', N'U') IS NOT NULL
    OR OBJECT_ID(N'dbo.LO_HANG', N'U') IS NOT NULL
    OR OBJECT_ID(N'dbo.TON_KHO', N'U') IS NOT NULL
    OR OBJECT_ID(N'dbo.SEQ_PHIEU_NHAP', N'SO') IS NOT NULL
    OR OBJECT_ID(N'dbo.SEQ_LO_HANG', N'SO') IS NOT NULL
    THROW 51800, N'Inbound inventory schema has already been applied or is partially present.', 1;
GO

SET XACT_ABORT ON;
BEGIN TRANSACTION;
CREATE TABLE dbo.PHIEU_NHAP (
    MaPN CHAR(6) NOT NULL CONSTRAINT PK_PHIEU_NHAP PRIMARY KEY,
    NgayNhap DATETIME2(3) NOT NULL
        CONSTRAINT DF_PHIEU_NHAP_NGAY DEFAULT (SYSUTCDATETIME()),
    MaNCC CHAR(6) NOT NULL,
    MaNV CHAR(6) NOT NULL,
    TrangThai NVARCHAR(20) NOT NULL
        CONSTRAINT DF_PHIEU_NHAP_TRANG_THAI DEFAULT (N'NHAP'),
    GhiChu NVARCHAR(1000) NULL,
    NgayHoanTat DATETIME2(3) NULL,
    CONSTRAINT FK_PHIEU_NHAP_NCC FOREIGN KEY (MaNCC)
        REFERENCES dbo.NHA_CUNG_CAP (MaNCC),
    CONSTRAINT FK_PHIEU_NHAP_NV FOREIGN KEY (MaNV)
        REFERENCES dbo.NHAN_VIEN (MaNV),
    CONSTRAINT CK_PHIEU_NHAP_TRANG_THAI
        CHECK (TrangThai IN (N'NHAP', N'DA_HOAN_THANH', N'DA_HUY')),
    CONSTRAINT CK_PHIEU_NHAP_HOAN_TAT CHECK (
        (TrangThai = N'DA_HOAN_THANH' AND NgayHoanTat IS NOT NULL)
        OR (TrangThai <> N'DA_HOAN_THANH' AND NgayHoanTat IS NULL)
    )
);
CREATE TABLE dbo.CT_PHIEU_NHAP (
    MaPN CHAR(6) NOT NULL,
    MaSP CHAR(6) NOT NULL,
    SoLuong INT NOT NULL,
    DonGiaNhap DECIMAL(19, 4) NOT NULL,
    CONSTRAINT PK_CT_PHIEU_NHAP PRIMARY KEY (MaPN, MaSP),
    CONSTRAINT FK_CT_PHIEU_NHAP_PN FOREIGN KEY (MaPN)
        REFERENCES dbo.PHIEU_NHAP (MaPN),
    CONSTRAINT FK_CT_PHIEU_NHAP_SP FOREIGN KEY (MaSP)
        REFERENCES dbo.SAN_PHAM (MaSP),
    CONSTRAINT CK_CT_PHIEU_NHAP_SO_LUONG CHECK (SoLuong > 0),
    CONSTRAINT CK_CT_PHIEU_NHAP_DON_GIA CHECK (DonGiaNhap >= 0)
);
CREATE TABLE dbo.LO_HANG (
    MaLo CHAR(6) NOT NULL CONSTRAINT PK_LO_HANG PRIMARY KEY,
    MaPN CHAR(6) NOT NULL,
    MaSP CHAR(6) NOT NULL,
    NgaySanXuat DATE NULL,
    HanSuDung DATE NULL,
    SoLuongNhap INT NOT NULL,
    CONSTRAINT FK_LO_HANG_CT_PN FOREIGN KEY (MaPN, MaSP)
        REFERENCES dbo.CT_PHIEU_NHAP (MaPN, MaSP),
    CONSTRAINT CK_LO_HANG_SO_LUONG CHECK (SoLuongNhap > 0),
    CONSTRAINT CK_LO_HANG_HAN CHECK (
        NgaySanXuat IS NULL OR HanSuDung IS NULL OR HanSuDung >= NgaySanXuat
    )
);
CREATE TABLE dbo.TON_KHO (
    MaViTri CHAR(6) NOT NULL,
    MaLo CHAR(6) NOT NULL,
    SoLuongTon INT NOT NULL,
    CONSTRAINT PK_TON_KHO PRIMARY KEY (MaViTri, MaLo),
    CONSTRAINT FK_TON_KHO_VI_TRI FOREIGN KEY (MaViTri)
        REFERENCES dbo.VI_TRI_KHO (MaViTri),
    CONSTRAINT FK_TON_KHO_LO FOREIGN KEY (MaLo)
        REFERENCES dbo.LO_HANG (MaLo),
    CONSTRAINT CK_TON_KHO_SO_LUONG CHECK (SoLuongTon >= 0)
);
CREATE SEQUENCE dbo.SEQ_PHIEU_NHAP AS INT START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE dbo.SEQ_LO_HANG AS INT START WITH 1 INCREMENT BY 1;
COMMIT TRANSACTION;
GO
